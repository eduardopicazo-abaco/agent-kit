const REPO = join(import.meta.dir, "..");

function errorsOf(tree: string, schemas: ReadonlyArray<string> = []): Issue[] {
  const root = materializeFixture(tree);
  if (schemas.length > 0) mkdirSync(join(root, "schemas"), { recursive: true });
  for (const id of schemas) {
    cpSync(join(REPO, "schemas", `${id}.schema.json`), join(root, "schemas", `${id}.schema.json`));
  }
  return runValidation(root).issues.filter((i) => i.severity === "error");
}

describe("the positive fixture", () => {
  test("a minimal well-formed tree validates clean", () => {
    const run = runValidation(materializeFixture("valid/minimal"));
    const loud = run.issues.filter((i) => i.severity !== "note");
    expect(loud.map((i) => `${i.rule} ${i.file}`)).toEqual([]);
    expect(run.ok).toBe(true);
  });

  test("the notes it does emit name the absent inputs rather than crashing", () => {
    const run = runValidation(materializeFixture("valid/minimal"));
    expect(run.issues.map((i) => i.rule)).toContain("provenance.lock-unavailable");
    expect(run.issues.map((i) => i.rule)).toContain("policy.invocation-unavailable");
  });

  test("its clean run covers schema conformance, and the positive control proves it", () => {
    // The fixture carried no `schemas/` and no `templates/` for most of its
    // life, so `checkSchemas` ran over it and contributed nothing. The one tree
    // whose entire job is to demonstrate that everything passes was not
    // demonstrating that schema conformance passes -- it was silent about it,
    // which reads the same way in the output.
    //
    // Adding the files is not on its own enough, because a fixture that nothing
    // validates against looks identical to one that validates clean. So this is
    // a positive control: break the template inside the materialized copy and
    // the same run has to fail. If it does not, the clean result above is
    // measuring nothing and this test is the only thing that would say so.
    const root = materializeFixture("valid/minimal");
    expect(runValidation(root).issues.filter((i) => i.severity === "error")).toEqual([]);

    writeFileSync(
      join(root, "templates/ticket.json"),
      JSON.stringify({ schema: "ticket", id: 7, title: "wrong type" }),
    );
    const broken = runValidation(root).issues.filter((i) => i.severity === "error");
    expect(broken.map((i) => i.rule)).toContain("schemas.document-invalid");
    expect(broken.some((i) => i.file === "templates/ticket.json")).toBe(true);
  });
});

describe("invalid fixtures", () => {
  for (const c of CASES) {
    test(`${c.tree}: ${c.what}`, () => {
      const errors = errorsOf(`invalid/${c.tree}`, c.schemas);
      const hit = errors.find((i) => i.rule === c.rule && i.file === c.file);
      expect({
        tree: c.tree,
        found: hit !== undefined,
        rules: [...new Set(errors.map((i) => i.rule))].sort(),
      }).toEqual({
        tree: c.tree,
        found: true,
        rules: [...new Set(c.rules ?? [c.rule])].sort(),
      });
      expect(hit?.message).toMatch(c.message);
    });
  }

  test("15-malformed-install measures the real install schema, not a copy that has drifted", () => {
    // The fixture carries its own schemas because a fixture tree is the whole
    // repository the validator sees. What it must not carry is a *different*
    // contract: a stale copy would go on passing while the real schema moved.
    const repo = join(import.meta.dir, "..");
    const fixture = join(import.meta.dir, "fixtures", "invalid", "15-malformed-install");
    expect(readFileSync(join(fixture, "schemas/install.schema.json"), "utf8")).toBe(
      readFileSync(join(repo, "schemas/install.schema.json"), "utf8"),
    );
    const common = (root: string) =>
      JSON.parse(readFileSync(join(root, "schemas/common.schema.json"), "utf8")).$defs.kebab_id;
    expect(common(fixture)).toEqual(common(repo));
  });

  test("every committed invalid fixture has a case asserting what it must report", () => {
    const dir = join(import.meta.dir, "fixtures", "invalid");
    const trees = readdirSync(dir).filter((n) => statSync(join(dir, n)).isDirectory());
    expect(trees.sort()).toEqual(CASES.map((c) => c.tree).sort());
  });
});

describe("the fixtures do not smuggle denied strings into the tree", () => {
  function fixtureFiles(dir: string): string[] {
    const out: string[] = [];
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) out.push(...fixtureFiles(full));
      else out.push(full);
    }
    return out;
  }

  test("no committed fixture file contains a denied term or an unfinished marker", () => {
    const terms = [...DENY_TERMS, ...PLACEHOLDER_TERMS];
    const hits: string[] = [];
    for (const file of fixtureFiles(join(import.meta.dir, "fixtures"))) {
      for (const hit of matchTerms(readFileSync(file, "utf8"), terms)) {
        hits.push(`${file}:${hit.line} ${hit.term.id}`);
      }
    }
    expect(hits).toEqual([]);
  });

  test("materializing a fixture substitutes the markers, so the scanner sees the real strings", () => {
    const body = readFileSync(
      join(materializeFixture("invalid/05-model-name-in-body"), "skills/alpha/SKILL.md"),
      "utf8",
    );
    expect(body).not.toContain("__DENY_MODEL_TERM__");
    expect(matchTerms(body, DENY_TERMS).length).toBeGreaterThan(0);
  });
});
