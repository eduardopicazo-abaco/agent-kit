/**
 * One deliberately-broken tree per case, each the smallest repository that can
 * hold the mistake. `rules` is the complete set of error rules the tree may
 * raise, so a fixture that starts failing for a second reason fails the test
 * rather than passing on the one rule it was written for.
 */
